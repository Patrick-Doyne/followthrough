/**
 * Generates src/theme-properties.css from the theme token list.
 *
 * <p>Run with `npx tsx scripts/gen-theme-properties.ts`. The output is
 * committed; this is not a build step.
 *
 * <p>Why it exists: a custom property is not animatable unless it has
 * been registered with `@property`, so the app's first attempt at a
 * theme cross-fade instead put a colour transition on *every element in
 * the document*. That had two visible faults. Anything painted from a
 * gradient jumped in one frame while its neighbours eased, because
 * `background-image` does not interpolate between arbitrary gradients.
 * And running thousands of simultaneous transitions dropped the page to
 * roughly nine frames per second, so even the parts that did fade
 * arrived in visible steps.
 *
 * <p>Registering the tokens moves the animation to the fifty-one
 * declarations on `:root`. Every consumer -- a flat background, a
 * gradient stop, a `color-mix`, an SVG stroke, a shadow -- then reads
 * one value that is already interpolating, so they cannot disagree
 * about where in the fade they are.
 *
 * <p>`initial-value` is the dark palette, which is the default theme,
 * so a token that somehow failed to parse would fall back to what the
 * app ships with rather than to transparent.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { DEFAULT_TRIAD, resolveAllPalettes, THEME_TOKEN_NAMES } from "../src/lib/theme.ts";

const OUT = fileURLToPath(new URL("../src/theme-properties.css", import.meta.url));
const DURATION = "300ms";
const EASING = "ease";

const dark = resolveAllPalettes(DEFAULT_TRIAD).dark;

const bad = THEME_TOKEN_NAMES.filter((n) => !/^oklch\([^)]*\)$/.test(dark[n] ?? ""));
if (bad.length)
  throw new Error(`not a plain oklch literal, cannot be an initial-value: ${bad.join(", ")}`);

const registrations = THEME_TOKEN_NAMES.map(
  (name) => `@property --${name} {
  syntax: "<color>";
  inherits: true;
  initial-value: ${dark[name]};
}`,
).join("\n\n");

const transitions = THEME_TOKEN_NAMES.map((name) => `    --${name} ${DURATION} ${EASING}`).join(
  ",\n",
);

writeFileSync(
  OUT,
  `/*
 * GENERATED by scripts/gen-theme-properties.ts -- do not edit by hand.
 *
 * Registers every theme token as an animatable <color>, and cross-fades
 * the whole palette by transitioning those ${THEME_TOKEN_NAMES.length} declarations on :root.
 *
 * The transition lives on one element rather than on every element in
 * the document. That is what makes the fade both smooth and uniform:
 * gradients, color-mix() and SVG paint all read the same interpolating
 * value, so nothing can arrive a frame ahead of anything else.
 *
 * See src/state/settings.ts -> beginThemeShift for when the class goes
 * on, and theme-properties.test.ts for the guard that keeps this file
 * in step with THEME_TOKEN_NAMES.
 */

${registrations}

/*
 * Applied for the length of the fade only. Colour transitions are not
 * something to leave switched on during navigation and scrolling, and
 * the people who asked not to be shown motion do not get this at all
 * -- see beginThemeShift.
 */
:root.theme-shifting {
  transition:
${transitions};
}
`,
);

console.log(`wrote ${OUT} (${THEME_TOKEN_NAMES.length} tokens)`);
