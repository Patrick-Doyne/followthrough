import { readFileSync } from "node:fs";

import { describe, expect, it } from "vitest";

import { DEFAULT_TRIAD, resolveAllPalettes, THEME_TOKEN_NAMES } from "@/lib/theme";

/**
 * The palette cross-fade only works for tokens that were registered.
 *
 * <p>An unregistered custom property is not animatable, so a token
 * missing from theme-properties.css would jump in one frame while the
 * rest of the palette eased around it -- which is the exact fault the
 * file was generated to remove, reappearing for one colour and only
 * during the 300ms of a theme change. Nothing else would catch it.
 *
 * <p>The file is generated by scripts/gen-theme-properties.ts. These
 * are the assertions that make regenerating it non-optional when a
 * token is added.
 */
const css = readFileSync(new URL("./theme-properties.css", import.meta.url), "utf8");

const registered = [...css.matchAll(/@property\s+--([\w-]+)\s*\{/g)].map((m) => m[1] as string);
const transitioned = [...css.matchAll(/^\s+--([\w-]+)\s+\d+ms/gm)].map((m) => m[1] as string);

describe("theme-properties.css", () => {
  it("registers exactly the theme tokens, no more and no fewer", () => {
    expect([...registered].sort()).toEqual([...THEME_TOKEN_NAMES].sort());
  });

  it("transitions every token it registers", () => {
    expect([...transitioned].sort()).toEqual([...registered].sort());
  });

  it("declares each one as an animatable colour that inherits", () => {
    // `syntax: "*"` would parse but would not animate, and a property
    // that does not inherit would leave every descendant on the
    // initial value instead of the palette.
    const blocks = [...css.matchAll(/@property\s+--[\w-]+\s*\{([^}]*)\}/g)].map((m) => m[1] ?? "");
    expect(blocks).toHaveLength(THEME_TOKEN_NAMES.length);
    for (const body of blocks) {
      expect(body).toContain('syntax: "<color>"');
      expect(body).toContain("inherits: true");
      expect(body).toMatch(/initial-value:\s*oklch\(/);
    }
  });

  it("initialises each token to the palette the app ships with", () => {
    // A registered property falls back to its initial value when a
    // declaration fails to parse. Pointing that at the default dark
    // palette means the failure mode is the shipped colour rather
    // than transparent.
    const dark = resolveAllPalettes(DEFAULT_TRIAD).dark;
    for (const [, name, value] of css.matchAll(
      /@property\s+--([\w-]+)\s*\{[^}]*initial-value:\s*([^;]+);/g,
    )) {
      expect(value?.trim(), name).toBe(dark[name as string]);
    }
  });

  it("scopes the transition to the class that is only on during a fade", () => {
    // Leaving colour transitions on permanently would drag every
    // navigation and hover through a 300ms fade.
    expect(css).toMatch(/:root\.theme-shifting\s*\{/);
  });
});
